let cart = JSON.parse(localStorage.getItem("valCart") || "[]"),
    wish = JSON.parse(localStorage.getItem("valWish") || "[]");

const $ = s => document.querySelector(s),
      $$ = s => document.querySelectorAll(s);

function save() {
  localStorage.setItem("valCart", JSON.stringify(cart));
  localStorage.setItem("valWish", JSON.stringify(wish));
  counts();
}

function counts() {
  $$(".cartCount").forEach(x => x.textContent = cart.reduce((a, b) => a + b.qty, 0));
  $$(".wishCount").forEach(x => x.textContent = wish.length);
}

function card(p) {
  return `
    <article class="product" onclick="openProduct(${p.id})">
      <button
        class="heart ${wish.includes(p.id) ? "liked" : ""}"
        onclick="event.stopPropagation();toggleWish(${p.id})"
      >
        ${wish.includes(p.id) ? "♥" : "♡"}
      </button>
      <div class="photo" style="background-image:url('${p.img}')"></div>
      <div class="info">
        <h3>${p.name}</h3>
        <p>${p.cat}</p>
        <div class="price">$${p.price.toLocaleString()}</div>
      </div>
    </article>
  `;
}

function render(list = products) {
  let e = $("#productGrid");

  if (e) {
    e.innerHTML = list.map(card).join("");

    let c = $("#productCount");

    if (c) c.textContent = list.length + " PIECES";
  }
}

function filterProducts(cat) {
    const list = cat === "all"
        ? products
        : products.filter(p => p.cat === cat);

    render(list);

    $$(".filter").forEach(b => {
        b.classList.toggle("active", b.dataset.cat === cat);
    });
}

function toggleWish(id) {
  wish.includes(id)
    ? wish = wish.filter(x => x !== id)
    : wish.push(id);

  save();
  render();
  toast(wish.includes(id) ? "Added to wishlist" : "Removed from wishlist");
}

function openProduct(id) {
  let p = products.find(x => x.id === id),
      m = $("#modalContent");

  if (!m) return;

  m.innerHTML = `
    <div class="modal-product">
      <img src="${p.img}" alt="${p.name}">
      <div>
        <p class="eyebrow">${p.cat}</p>
        <h2>${p.name}</h2>
        <div class="price">$${p.price.toLocaleString()}</div>
        <p class="desc">${p.desc}</p>

        <div class="qty">
          <button onclick="changeQty(-1)">−</button>
          <input id="qty" type="number" min="1" value="1">
          <button onclick="changeQty(1)">+</button>
        </div>

        <button
          class="gold-btn"
          style="width:100%"
          onclick="addCart(${p.id},+$('#qty').value);closeModal()"
        >
          ADD TO BAG
        </button>
      </div>
    </div>
  `;

  $("#productModal").classList.add("open");
}

function changeQty(n) {
  let x = $("#qty");
  x.value = Math.max(1, +x.value + n);
}

function addCart(id, qty = 1) {
  let x = cart.find(a => a.id === id);

  x
    ? x.qty += Math.max(1, qty)
    : cart.push({ id, qty: Math.max(1, qty) });

  save();
  toast("Added to your bag");
  openCart();
}

function renderCart() {
  let e = $("#cartItems");

  if (!e) return;

  if (!cart.length) {
    e.innerHTML = '<p class="empty">Your bag is waiting for something beautiful.</p>';
  } else {
    e.innerHTML = cart.map((x, i) => {
      let p = products.find(a => a.id === x.id);

      return `
        <div class="cart-row">
          <img src="${p.img}" alt="${p.name}">
          <div>
            <h3>${p.name}</h3>
            <div class="price">$${p.price.toLocaleString()} × ${x.qty}</div>
            <button class="remove" onclick="removeCart(${i})">REMOVE</button>
          </div>
        </div>
      `;
    }).join("");
  }

  let total = cart.reduce(
    (a, x) => a + products.find(p => p.id === x.id).price * x.qty,
    0
  );

  if ($("#cartTotal")) {
    $("#cartTotal").textContent = "$" + total.toLocaleString();
  }

  if ($("#cartTotal2")) {
    $("#cartTotal2").textContent = "$" + total.toLocaleString();
  }

  counts();
}

function removeCart(i) {
  cart.splice(i, 1);
  save();
  renderCart();
  toast("Item removed");
}

function openCart() {
  renderCart();

  let d = $("#cartDrawer");

  if (d) d.classList.add("open");
}

function closeModal() {
  let m = $("#productModal");

  if (m) m.classList.remove("open");
}

function openSearch() {
  let s = $("#searchPanel");

  if (s) {
    s.classList.add("open");
    setTimeout(() => $("#searchInput").focus(), 100);
  }
}

function doSearch(v) {
  let q = v.trim().toLowerCase();

  let input = $("#searchInput");
  if (input) input.value = "";

  if (!q) {
    render(products);
    return;
  }

  let results = products.filter(p =>
    p.name.toLowerCase().includes(q) ||
    p.cat.toLowerCase().includes(q)
  );

  render(results);
}

function checkout() {
  if (!cart.length) return toast("Your bag is empty");

  location.href = "checkout.html";
}

function toast(msg) {
  let t = $("#toast");

  if (!t) return;

  t.textContent = msg;
  t.classList.add("show");

  setTimeout(() => t.classList.remove("show"), 2200);
}

function newsletter(e) {
  e.preventDefault();
  toast("Welcome to the Valentino world.");
  e.target.reset();
}

document.addEventListener("DOMContentLoaded", () => {
  counts();
  if (document.getElementById("productGrid")) {
  const isHome =
    location.pathname.endsWith("index.html") ||
    location.pathname === "/" ||
    location.pathname.endsWith("/");

  render(isHome ? products.slice(0, 10) : products);
}

  $$(".filter").forEach(
    b => b.onclick = () => filterProducts(b.dataset.cat)
  );

  $$("[data-open-cart]").forEach(b => b.onclick = openCart);
  $$("[data-search]").forEach(b => b.onclick = openSearch);

  $$("[data-close]").forEach(
    b => b.onclick = () => {
      let e = $(b.dataset.close);

      if (e) e.classList.remove("open");
    }
  );

  let i = $("#searchInput");

if (i) {
  i.addEventListener("keydown", e => {
    if (e.key === "Enter") {
      e.preventDefault();

      doSearch(i.value);

      let searchPanel = $("#searchPanel");
      if (searchPanel) {
        searchPanel.classList.remove("open");
      }

      let productGrid = $("#productGrid");
      if (productGrid) {
        productGrid.scrollIntoView({
          behavior: "smooth",
          block: "start"
        });
      }
    }
  });
}
  let p = new URLSearchParams(location.search),
      term = p.get("search");

  if (term && $("#productGrid")) {
    render(
      products.filter(
        x =>
          x.name.toLowerCase().includes(term.toLowerCase()) ||
          x.cat.includes(term.toLowerCase())
      )
    );
  }
});

function toggleMobileMenu() {
  const menu = document.getElementById("mobileNav");

  if (menu) {
    menu.classList.toggle("open");
  }
}
